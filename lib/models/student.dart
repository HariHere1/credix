class Student {
  final String id;
  final String name;
  final String rollNo;
  final String email;
  final String batch;
  final String department;
  final String password;

  const Student({
    required this.id,
    required this.name,
    required this.rollNo,
    required this.email,
    required this.batch,
    required this.department,
    required this.password,
  });
}
